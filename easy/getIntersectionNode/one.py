class Solution(object):
    def getIntersectionNode(self, headA, headB):
        """
        The idea is to use two pointers and then assign to the other head for the pointer if it ends so that
        both will travel the same distance A + B or B + A and based on that will return if they have the 
        intersection node or not.
        """
        p1 = headA
        p2 = headB

        while p1 != p2:
            p1 = p1.next if p1 else headB
            p2 = p2.next if p2 else headA
        
        return p1
